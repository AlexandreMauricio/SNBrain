# Usage (from the vault root):  powershell -ExecutionPolicy Bypass -File _meta/tools/docs-vs-reality.ps1
# Rebuilds _meta/Docs vs Reality.md: every place the vault records that a claim was contradicted,
# that an instance behaved differently from the docs, or that two sources disagree.
# Surfacing step of the improvement loop (_meta/Procedures/Improvement Loop.md).

$root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$out = Join-Path $root "_meta\Docs vs Reality.md"

function Clean([string]$s) {
    $s = [regex]::Replace($s, '\[\[([^\]\|]+)\|([^\]]+)\]\]', '$2')
    $s = [regex]::Replace($s, '\[\[([^\]]+)\]\]', '$1')
    $s = $s -replace '^\s*(\d+\.|-|\*)\s*', '' -replace '\s+', ' '
    $s = $s.Trim()
    if ($s.Length -gt 260) { $s = $s.Substring(0, 257) + '...' }
    return $s
}

$contra = '(?i)\(contradicted|\(outdated from'
$inst = '(?i)differs? from the (docs|guide)|(docs|guide) (says?|said|describes?|claims?)[^.]*but|unlike the (docs|guide)|not as (documented|the docs)|contrary to the (docs|guide)|the docs are wrong|instead of what the (docs|guide)'
$src = '(?i)discrepanc|disagrees? with|\bconflicts? with the'

$files = Get-ChildItem -Path $root -Recurse -Filter *.md | Where-Object {
    $_.FullName -notmatch '\\\.git\\|\\\.obsidian\\|\\Templates\\|\\_meta\\' -and $_.Name -notin @('_index.md', 'README.md', 'CLAUDE.md')
}
$sections = [ordered]@{ 'Contradicted or outdated claims' = @{}; 'Instance behaviour different from the docs' = @{}; 'Sources that disagree with each other' = @{} }
$n = 0
foreach ($f in $files) {
    $c = [IO.File]::ReadAllText($f.FullName, [Text.Encoding]::UTF8)
    $status = ''; $observed = ''; $body = $c
    if ($c -match '(?s)^---\r?\n(.*?)\r?\n---\r?\n(.*)$') {
        $fm = $Matches[1]; $body = $Matches[2]
        if ($fm -match '(?m)^status:\s*(\S+)') { $status = $Matches[1] }
        if ($fm -match '(?m)^observed-in:\s*\[?([^\]\r\n]*)') { $observed = $Matches[1].Trim() }
    }
    $fromInstance = ($status -eq 'verified' -or $observed)
    $inCode = $false
    foreach ($line in ($body -split '\r?\n')) {
        if ($line -match '^```') { $inCode = -not $inCode; continue }
        if ($inCode -or $line -match '^#') { continue }
        $key = $null
        if ($line -match $contra) { $key = 'Contradicted or outdated claims' }
        elseif ($fromInstance -and ($line -match $inst -or $line -match '(?i)(observed|tested|verified|seen) in [^.]*(docs|guide)')) { $key = 'Instance behaviour different from the docs' }
        elseif ($line -match $inst) { $key = 'Sources that disagree with each other' }
        elseif ($line -match $src) { $key = 'Sources that disagree with each other' }
        if (-not $key) { continue }
        $label = "[[$($f.BaseName)]] ($status"
        if ($observed) { $label += "; observed in $observed" }
        $label += ')'
        if (-not $sections[$key].ContainsKey($label)) { $sections[$key][$label] = New-Object System.Collections.Generic.List[string] }
        $sections[$key][$label].Add((Clean $line)); $n++
    }
}

$today = Get-Date -Format 'yyyy-MM-dd'
$sb = New-Object Text.StringBuilder
foreach ($l in @('---', 'type: meta', 'tags: [meta]', 'status: documented', 'source: generated by _meta/tools/docs-vs-reality.ps1, do not edit by hand', "updated: $today", '---', '', '# Docs vs reality', '')) { [void]$sb.AppendLine($l) }
[void]$sb.AppendLine("**Generated ${today}: $n lines.** Where the vault records that the real system, a newer build or another source disagrees with what a note says. These are the vault's most valuable findings: check them before trusting the docs on the same topic, and settle each one in an instance when you can ([[Improvement Loop]]). Regenerate with ``powershell -ExecutionPolicy Bypass -File _meta/tools/docs-vs-reality.ps1``.")
foreach ($k in $sections.Keys) {
    $s = $sections[$k]
    [void]$sb.AppendLine(''); [void]$sb.AppendLine("## $k ($($s.Count) notes)"); [void]$sb.AppendLine('')
    foreach ($label in ($s.Keys | Sort-Object)) {
        [void]$sb.AppendLine("- $label")
        foreach ($i in ($s[$label] | Select-Object -Unique)) { [void]$sb.AppendLine("    - $i") }
    }
}
[IO.File]::WriteAllText($out, $sb.ToString().Replace("`r`n", "`n"), (New-Object Text.UTF8Encoding($false)))
"wrote $out : $n lines"
